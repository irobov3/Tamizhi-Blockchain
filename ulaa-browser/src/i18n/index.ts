export type I18nKey = keyof typeof ta;

let currentLang: 'ta' | 'en' = 'ta';
export const setLang = (l: 'ta' | 'en') => { currentLang = l; };
export const getLang = () => currentLang;

export function t(key: I18nKey): string {
  const map = currentLang === 'ta' ? ta : en;
  return (map as any)[key] ?? (ta as any)[key] ?? key;
}

export function tArr(key: I18nKey): string[] {
  const map = currentLang === 'ta' ? ta : en;
  const val = (map as any)[key];
  return Array.isArray(val) ? val : [];
}
