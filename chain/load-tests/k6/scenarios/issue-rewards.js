/**
 * issue-rewards.js
 *
 * Stress-tests the IssueReward write path against the Tamizhi chain.
 *
 * Stages:
 *   low    –  5 VUs for 30 s
 *   medium – 20 VUs for 30 s (starts at t=35 s)
 *   high   – ramp 20→50 VUs  (starts at t=70 s)
 *
 * NOTE: k6 cannot sign Cosmos transactions natively.  Real production load
 * tests should pre-sign tx bytes offline (e.g. with cosmjs + a Node.js
 * script) and replay them here.  This scenario simulates the full request
 * latency profile (query + broadcast round-trips) so the chain's HTTP layer,
 * ante-handler, and mempool are exercised even when tx bytes are invalid.
 */

import http from 'k6/http';
import { check, sleep } from 'k6';
import { txLatency, txSuccess, txFailed, txSuccessRate } from '../helpers.js';

// ---------------------------------------------------------------------------
// Scenario configuration
// ---------------------------------------------------------------------------
export const options = {
  scenarios: {
    low_load: {
      executor: 'constant-vus',
      vus: 5,
      duration: '30s',
      tags: { scenario: 'low' },
    },
    medium_load: {
      executor: 'constant-vus',
      vus: 20,
      duration: '30s',
      startTime: '35s',
      tags: { scenario: 'medium' },
    },
    high_load: {
      executor: 'ramping-vus',
      startVUs: 20,
      stages: [
        { duration: '30s', target: 50 },
        { duration: '30s', target: 50 },
        { duration: '15s', target: 0 },
      ],
      startTime: '70s',
      tags: { scenario: 'high' },
    },
  },
  thresholds: {
    // At least 95 % of broadcast calls must reach the chain without a 5xx
    tx_success_rate: ['rate>0.95'],
    // p95 confirmation latency under 8 s (covers mempool wait + block commit)
    tx_confirmation_latency_ms: ['p(95)<8000'],
    // Individual REST calls complete within 2 s at p99
    http_req_duration: ['p(99)<2000'],
  },
  summaryTrendStats: ['min', 'med', 'avg', 'p(90)', 'p(95)', 'p(99)', 'max'],
};

// ---------------------------------------------------------------------------
// Default function – executed by every VU on every iteration
// ---------------------------------------------------------------------------
export default function () {
  const restUrl = __ENV.REST_URL || 'http://localhost:1317';

  // Unique identifiers scoped to this VU + iteration to avoid collisions
  const employeeId = `emp-${__VU}-${__ITER}-${Math.floor(Math.random() * 10000)}`;

  // ── Phase 1: Read ────────────────────────────────────────────────────────
  // Query existing reward records for this employee.
  // A 404 is acceptable for new employees; anything else is a problem.
  const queryRes = http.get(
    `${restUrl}/tamizhi/rewards/v1/records/${employeeId}`,
    { tags: { name: 'QueryRewardRecords' } }
  );

  check(queryRes, {
    'query: status 200 or 404': (r) => r.status === 200 || r.status === 404,
    'query: response time < 500 ms': (r) => r.timings.duration < 500,
  });

  // ── Phase 2: Write ───────────────────────────────────────────────────────
  // Broadcast a MsgIssueReward transaction.
  //
  // Production usage: replace `tx_bytes` with real base64-encoded, pre-signed
  // protobuf bytes generated by a signing script (cosmjs, Go test binary, …).
  // The chain's ante-handler will reject the placeholder bytes, but the HTTP
  // round-trip and mempool acceptance path are still fully exercised.
  const start = Date.now();

  const writeRes = http.post(
    `${restUrl}/cosmos/tx/v1beta1/txs`,
    JSON.stringify({
      // PLACEHOLDER – replace with real signed tx bytes for genuine load
      tx_bytes: 'AAAA',
      mode: 'BROADCAST_MODE_SYNC',
    }),
    {
      headers: { 'Content-Type': 'application/json' },
      tags: { name: 'BroadcastIssueReward' },
    }
  );

  const latency = Date.now() - start;
  txLatency.add(latency);

  // 200 = valid tx accepted; 400 = expected for placeholder bytes (ante-handler
  // rejection is a normal response, not a server error).
  // Anything 5xx means the chain itself is struggling.
  if (writeRes.status === 200 || writeRes.status === 400) {
    txSuccess.add(1);
    txSuccessRate.add(true);
  } else {
    txFailed.add(1);
    txSuccessRate.add(false);
    console.warn(`Unexpected broadcast status ${writeRes.status}: ${writeRes.body}`);
  }

  check(writeRes, {
    'broadcast: no 5xx': (r) => r.status < 500,
    'broadcast: has response body': (r) => r.body && r.body.length > 0,
  });

  // Small pause to avoid saturating a single VU's TCP connection pool
  sleep(0.1);
}
